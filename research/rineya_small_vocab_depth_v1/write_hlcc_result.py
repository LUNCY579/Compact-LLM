"""HLCC-001 -- render HLCC001_RESULT.md FROM the artifacts (no number hand-copied).

Reads HLCC_RESULT.json and the panel; scores the §7 forecasts and applies the §8 licensing rule in code;
adds the post-hoc per-category answer-likelihood breakdown, labelled DESCRIPTIVE (not registered, not a
test). Create-only output.
usage: python write_hlcc_result.py --result <HLCC_RESULT.json> --panel <CONFIRM_PANEL.jsonl> --out <md>
       [--log <run log>]
"""
from __future__ import annotations

import argparse
import collections
import json
import math
import statistics as st
from pathlib import Path


def f3(x):
    return f"{x:.3g}"


def licence(v: dict) -> str:
    """HLCC001_PREREG.md §8, as registered (R2)."""
    if v["verdict"] == "CONFIRMED" and v["size_large"]:
        return ("CONFIRMED with size_large: the LC-folded V4/20 becomes the recommended INITIALISATION for any "
                "future recovery or distillation training (still requires G5, a training lane, the teacher "
                "decision and a grant permitting architectural change)")
    if v["verdict"] == "CONFIRMED":
        return ("CONFIRMED without size_large: the DIRECTION only is licensed -- among rows from these pools, with "
                "this T, more rows improve than worsen on both measures; the initialisation recommendation does "
                "NOT change")
    return {"PARTIAL": "PARTIAL: only the confirmed measure is licensed (§8)",
            "NOT_CONFIRMED": "NOT_CONFIRMED: LC is not recommended",
            "HARMFUL": "HARMFUL: LC is barred for this student"}[v["verdict"]]


def main(argv=None) -> int:
    ap = argparse.ArgumentParser()
    ap.add_argument("--result", required=True, type=Path)
    ap.add_argument("--panel", required=True, type=Path)
    ap.add_argument("--out", required=True, type=Path)
    ap.add_argument("--log", type=Path)
    a = ap.parse_args(argv)
    if a.out.exists():
        raise SystemExit(f"{a.out} exists (create-only)")
    r = json.loads(a.result.read_text(encoding="utf-8"))
    rows = {x["id"]: x for x in map(json.loads, a.panel.read_text(encoding="utf-8").splitlines())}
    P, S = r["sets"]["primary"], r["sets"]["secondary"]
    V = P["VERDICT"]
    L = []
    w = L.append
    w("# HLCC-001 — result\n")
    w(f"**Generated by `write_hlcc_result.py` from `rineya-dataset-retention-records/hlcc001-20260925/result/"
      f"HLCC_RESULT.json`**; no number was hand-copied. "
      f"Registration: `HLCC001_PREREG.md` (267cec9b, R1 d321280c, R2 bf617378, launcher 8db8858e).\n")
    w(f"**Registered verdict (PRIMARY, V4_32768/20): {r['REGISTERED_VERDICT']}** · size_large = "
      f"**{V['size_large']}** · §8 licence: {licence(V)}.\n")
    w("**Independent cold read:** Rineya Delta scored §7 and §8 blind from the JSON (records b8eb3a7), then compared "
      "with this document (e17e1d0): every number recomputed with independent binomial and order-statistic code "
      "matches; forecasts 5/7; the §8 reading \"CONFIRMED without size_large, so direction only\" is confirmed. "
      "`hlcc001-20260925/HLCC_RESULT_COLD_READ.md`.\n")
    w("## Run integrity\n")
    w(f"- One attempt, rc 0, lease `hlcc001` acquired and released; no attempt records (no failure after the "
      f"panel boundary).")
    w(f"- Refusal controls passed on the real teacher before the panel was read: identity fold ×2 (bitwise), "
      f"fit canary **{r['fit_canary']['status']}** (largest difference {r['fit_canary']['max_abs_diff']} against "
      f"SMALLVD-001's recorded GPU residuals, tolerance {r['fit_canary']['tolerance']}), vocabulary check.")
    w(f"- Hashes recorded by the run: panel `{r['confirm_panel_sha256'][:8]}`, all-axis map "
      f"`{r['allaxis_map_sha256'][:8]}`, `run_hlcc.py` `{r['runtime']['code_sha256']['run_hlcc.py'][:8]}`, "
      f"`hlcc_verdict.py` `{r['runtime']['code_sha256']['hlcc_verdict.py'][:8]}` — the registered values. "
      f"Device {r['runtime']['device']}, torch {r['runtime']['torch']}, TF32 {r['runtime']['flags']['tf32']}.\n")
    w("## Registered test (row-level exact sign tests, α = 0.0125 each)\n")
    w("| set | limb | rows better | p (better) | p (worse) | median lower bound → min median reduction | verdict | size_large |")
    w("|---|---|---|---|---|---|---|---|")
    for role, s in (("**PRIMARY** V4/20", P), ("SECONDARY 18-block (replication)", S)):
        v = s["VERDICT"]
        for lim, name in (("kl", "KL (teacher head: depth only)"), ("bpb", "answer nats (the set's own vocabulary)")):
            x = v[lim]
            w(f"| {role} | {name} | {x['positive']}/{x['n']} (ties {x['ties_dropped']}) | {f3(x['p_greater'])} | "
              f"{f3(x['p_less'])} | {x['median_lower_bound']:.3f} → ×{x['min_median_reduction_factor']:.3f} | "
              f"{v['verdict']} | {v['size_large']} |")
    w(f"\nThe size bar is ×{V['large_bar_factor']:.2f} on BOTH limbs. PRIMARY clears it on KL and misses it on "
      f"answer nats (certified ×{V['bpb']['min_median_reduction_factor']:.3f}); the SECONDARY clears both.\n")
    w("## Registered sensitivity analysis (all-axis units, majority sign, direction only)\n")
    w("| set | KL units better | p | bpb units better | p | verdict |")
    w("|---|---|---|---|---|---|")
    for role, s in (("PRIMARY", P), ("SECONDARY", S)):
        z = s["sensitivity_allaxis_majority_sign"]
        w(f"| {role} | {z['kl']['positive']}/{z['kl']['n']} | {f3(z['kl']['p_greater'])} | "
          f"{z['bpb']['positive']}/{z['bpb']['n']} | {f3(z['bpb']['p_greater'])} | {z['verdict']} |")
    w("\nThe direction survives collapsing every shared generator (121 KL / 36 bpb units before ties).\n")

    # forecasts, scored in code
    d = P["descriptive"]
    fk = V["kl"]["positive"] / V["kl"]["n"]
    fb = V["bpb"]["positive"] / V["bpb"]["n"]
    corr = d["shape_of_log_lc_over_plain"]["corr_logkl_logratio"]
    fc = [("F1", "PRIMARY KL rows better ≥ 0.90", f"{fk:.3f}", fk >= 0.90),
          ("F2", "PRIMARY bpb rows better ≥ 0.80", f"{fb:.3f}", fb >= 0.80),
          ("F3", "size_large", str(V["size_large"]), bool(V["size_large"])),
          ("F4", "corr(log KL_plain, log(LC/plain)) < 0", f"{corr:+.3f}", corr < 0),
          ("F5", "SECONDARY CONFIRMED", S["VERDICT"]["verdict"], S["VERDICT"]["verdict"] == "CONFIRMED"),
          ("F6", "LC flip rate < plain (PRIMARY, teacher-vocabulary generations)", f"{d['flip_rate']['lc']:.3f} vs {d['flip_rate']['plain']:.3f}",
           d["flip_rate"]["lc"] < d["flip_rate"]["plain"]),
          ("F7", "sensitivity agrees in direction on KL", P["sensitivity_allaxis_majority_sign"]["kl"]["p_greater"] < 0.0125 and "yes" or "no",
           P["sensitivity_allaxis_majority_sign"]["kl"]["p_greater"] < 0.0125)]
    w("## Registered forecasts (§7; not gates)\n")
    w("| | forecast | observed | |")
    w("|---|---|---|---|")
    for k, t, o, ok in fc:
        w(f"| {k} | {t} | {o} | {'MET' if ok else '**MISSED**'} |")
    w(f"\n{sum(ok for *_, ok in fc)}/7 met. The two misses are correlated misses on the SAME limb (answer nats on "
      f"the recommended student): F2 is the fraction of rows improving and F3 the certified median bound -- they "
      f"can come apart, and here both fall short. The KL bound (x{V['kl']['min_median_reduction_factor']:.3f}) is a "
      f"bound, and size_large is a JOINT annotation: the KL limb alone is not called large.\n")

    w("## Descriptive (registered as descriptive; never a verdict)\n")
    w("| | PRIMARY plain → LC | SECONDARY plain → LC |")
    w("|---|---|---|")
    for key, lab in (("V0", "answer bpb, teacher vocabulary"), ("primary_vocab", "answer bpb, V4"),
                     ("secondary_vocab", "answer bpb, V2")):
        w(f"| {lab} | {P['descriptive']['answer_bpb'][key]['plain']:.4f} → {P['descriptive']['answer_bpb'][key]['lc']:.4f} | "
          f"{S['descriptive']['answer_bpb'][key]['plain']:.4f} → {S['descriptive']['answer_bpb'][key]['lc']:.4f} |")
    w(f"| category-mean KL | {P['descriptive']['category_mean_kl']['plain']:.4f} → {P['descriptive']['category_mean_kl']['lc']:.4f} "
      f"(r = {1 - P['descriptive']['category_mean_kl']['lc'] / P['descriptive']['category_mean_kl']['plain']:.3f}) | "
      f"{S['descriptive']['category_mean_kl']['plain']:.4f} → {S['descriptive']['category_mean_kl']['lc']:.4f} "
      f"(r = {1 - S['descriptive']['category_mean_kl']['lc'] / S['descriptive']['category_mean_kl']['plain']:.3f}) |")
    w(f"| flip rate vs teacher (teacher-vocabulary generations) | {P['descriptive']['flip_rate']['plain']:.3f} → {P['descriptive']['flip_rate']['lc']:.3f} | "
      f"{S['descriptive']['flip_rate']['plain']:.3f} → {S['descriptive']['flip_rate']['lc']:.3f} |")
    w(f"| median row d_kl → ratio | ×{math.exp(st.median(P['per_row']['d_kl'].values())):.2f} | ×{math.exp(st.median(S['per_row']['d_kl'].values())):.2f} |")
    w(f"| median row d_bpb → ratio | ×{math.exp(st.median(P['per_row']['d_bpb'].values())):.3f} | ×{math.exp(st.median(S['per_row']['d_bpb'].values())):.3f} |")
    w("")
    w("### POST-HOC, NOT REGISTERED: answer likelihood by category\n")
    w("Computed after the verdict from the recorded per-row values. Eight strata, no multiplicity control, "
      "no test: **a lead for a new registered hypothesis, not a finding.**\n")
    w("| stratum | PRIMARY rows better | median ratio | SECONDARY rows better | median ratio |")
    w("|---|---|---|---|---|")
    strata = collections.OrderedDict()
    mixed = {rows[i]["category"] for i in P["per_row"]["d_bpb"] if rows[i]["reference"] == "UNKNOWN"}
    for role, s in (("p", P), ("s", S)):
        for i, v in s["per_row"]["d_bpb"].items():
            cat = rows[i]["category"]
            c = cat + ((" — reference UNKNOWN" if rows[i]["reference"] == "UNKNOWN" else " — known answer")
                       if cat in mixed else "")
            strata.setdefault(c, {"p": [], "s": []})[role].append(v)
            if cat in mixed:
                strata.setdefault(cat + " — ALL rows", {"p": [], "s": []})[role].append(v)
    for c in sorted(strata):
        cp, cs = strata[c]["p"], strata[c]["s"]
        w(f"| {c} | {sum(v > 0 for v in cp)}/{len(cp)} | ×{math.exp(st.median(cp)):.3f} | "
          f"{sum(v > 0 for v in cs)}/{len(cs)} | ×{math.exp(st.median(cs)):.3f} |")
    w("\n**The one reversal worth a registered follow-up:** on the recommended V4/20 student, compensation makes "
      "the reference answer `UNKNOWN` LESS likely in most abstention rows, while on the 18-block set it makes it "
      "more likely in every one. Abstention is the programme's most fragile axis (DOSEINT-001's abstention "
      "collapse), so the V4/20 direction-only licence must not be read as licensing abstention. The recorded data "
      "cannot separate the two candidate causes -- the depth set (PRIMARY keeps blocks 7 and 19) and the V4 "
      "re-tokenisation -- because per-row values were stored only in each set's own vocabulary. The panel's read "
      "is spent; a follow-up needs a fresh panel and its own registration.\n")
    w("## What this does NOT change\n")
    w("- GO/HOLD stays **HOLD** (none of its missing limbs is touched). No quality claim, no release.")
    w("- The claim covers the panel's sampling pools with this T, not new books, generators or packages.")
    w("- Nothing here selects a set, a λ or a fold point.")
    if a.log and a.log.exists():
        w("\n## Run log\n\n```")
        w(a.log.read_text(encoding="utf-8").strip())
        w("```")
    with open(a.out, "x", encoding="utf-8", newline="\n") as f:
        f.write("\n".join(L) + "\n")
    print(f"wrote {a.out}: verdict {r['REGISTERED_VERDICT']}, size_large {V['size_large']}, forecasts met "
          f"{sum(ok for *_, ok in fc)}/7")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
