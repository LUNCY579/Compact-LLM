"""SMALLVD-001 -- compose the results document FROM THE ARTIFACTS (no number is hand-copied).

Reads the records namespace (G0 lineage, vocabulary candidates and rule-1 corrections, G0b, the layer
report, the surgery arm gates, the architecture manifests, the H-LC arms) and go_hold.decide, and
renders SMALLVD001_RESULTS.md. Every artifact that does not exist yet renders as "pending", so the
same script produces a partial draft now and the final document later. Deliverable numbers follow
the operator's brief.
usage: python write_results.py --records <smallvd001 dir> --out <file.md>
"""
from __future__ import annotations

import argparse
import json
import subprocess
from pathlib import Path

HERE = Path(__file__).resolve().parent


def _j(p: Path):
    return json.loads(p.read_text(encoding="utf-8")) if p.exists() else None


def f(x, nd=4):
    return "—" if x is None else (f"{x:,}" if isinstance(x, int) else f"{x:.{nd}f}")


def main(argv=None) -> int:
    import sys
    sys.path.insert(0, str(HERE))
    import go_hold
    import param_accounting as pa
    ap = argparse.ArgumentParser()
    ap.add_argument("--records", required=True, type=Path)
    ap.add_argument("--out", required=True, type=Path)
    a = ap.parse_args(argv)
    R = a.records
    md = ["# SMALLVD-001 — results (generated by `write_results.py` from the records; no number hand-copied)\n",
          "**Surgery-only and structural.** `quality_claim: false`, `release_permitted: false`. "
          "Registration: `SMALLVD001_PREREG.md` with Amendments 1–6.\n"]
    head = subprocess.run(["git", "-C", str(HERE), "rev-parse", "HEAD"], capture_output=True, text=True).stdout.strip()
    md += ["## 1. Branch\n", f"`research/rineya-small-vocab-depth-distill-v1` at `{head}` (remote-backed).\n"]

    g0 = _j(R / "G0_TEACHER_LINEAGE.json")
    md.append("## 2. Teacher lineage (G0)\n")
    if g0:
        ok = all(v["match"] for v in g0["recorded_hash_comparison"].values())
        md.append(f"Compression subject `{Path(g0['teacher_dir']).name}`; weights data-section sha256 "
                  f"`{g0['weights_data_section_sha256'][:16]}…`; {len(g0['recorded_hash_comparison'])} recorded hashes "
                  f"{'all match' if ok else 'DO NOT all match'}. Distillation teacher: UNRESOLVED (operator decision).\n")
    else:
        md.append("pending\n")

    md.append("## 3 / 14. Exact parameter accounting (P = 1024·V + 15,730,944·L + 1024)\n")
    cfg = json.loads((Path(g0["teacher_dir"]) / "config.json").read_text(encoding="utf-8")) if g0 else None
    if cfg:
        vs, ds = pa.VOCAB_GRID, (28, 24, 20, 18, 16, 12)
        md += ["| vocab rows \\ blocks | " + " | ".join(map(str, ds)) + " |", "|---|" + "---:|" * len(ds)]
        for name, rows in vs.items():
            md.append(f"| {name} {rows:,} | " + " | ".join(f"{pa.analytic(cfg, rows, L)['unique_physical_parameters']:,}"
                                                         for L in ds) + " |")
        md.append("")

    vc, rc = _j(R / "vocab" / "VOCAB_CANDIDATES.json"), _j(R / "vocab" / "VOCAB_RULE1_CORRECTIONS.json")
    ps = _j(R / "vocab" / "PROTECTED_SET.json")
    md.append("## 4–7. Vocabulary profiling, protected tokens, candidates, validation (G1)\n")
    if vc and rc:
        if ps:
            md.append(f"Protected set: {ps['union']:,} tokens ({', '.join(f'{k} {v:,}' for k, v in ps['counts'].items())}); "
                      f"closure with merge ancestors {ps['closure_including_ancestors']:,}.\n")
        md += ["| candidate | rows | HELD-OUT token ratio | P99 row ratio | 1-token words split | word invariance (violations / qualifying) | registered verdict | rule 1'' |",
               "|---|---:|---:|---:|---:|---:|---|---|"]
        for name, c in vc["candidates"].items():
            key = f"{name}_{c['rows']}"
            wi = c.get("word_invariance", {})
            md.append(f"| {name} | {c['rows']:,} | {c['heldout']['all']['token_ratio']:.4f} | {c['heldout']['all']['ratio_p99']:.3f} | "
                      f"{c['word_fragmentation']['single_token_words_now_split_occurrence_rate']:.4f} | "
                      f"{wi.get('violations', '—')} / {wi.get('qualifying_distinct', '—'):,} | {c['verdict']} | "
                      f"{rc['candidates'][key]['rule1_double_prime']} |")
        md.append(f"\nThe registered REJECT (rule 1, canonical ORDER) fired on one HELD-OUT row the unpruned teacher also fails; "
                  f"under rule 1'' (canonical EQUIVALENCE, Amendment 6) the teacher and every candidate pass. "
                  f"Teacher fails rule 1 on {rc['teacher_fails_registered_rule1']}, rule 1'' on {rc['teacher_fails_rule1_double_prime'] or 'nothing'}.\n")
    else:
        md.append("pending\n")

    g0b = _j(R / "G0B_BASELINE_REPRODUCTION.json")
    md += ["## Baseline reproduction (G0b)\n",
           (f"{g0b['text_identical_rows']}/{g0b['rows']} text-identical to the recorded Supa predictions "
            f"({g0b['decoding']['dtype']}, {g0b['decoding']['attn_implementation']}, batch {g0b['decoding']['batch']}).\n")
           if g0b else "pending\n"]

    rep = _j(R / "layer_study" / "LAYER_REPORT.json")
    md.append("## 8–9. Layer ablation and ranking\n")
    if rep:
        single = sorted(rep["single_layer"], key=lambda r: r["holdout_objective"])
        md.append("Least damaging single-block bypasses (HOLDOUT category-mean KL): " +
                  ", ".join(f"L{r['layer']} {r['holdout_objective']:.3f}" for r in single[:6]) +
                  ". Most damaging: " + ", ".join(f"L{r['layer']} {r['holdout_objective']:.3f}" for r in single[-4:]) + ".\n")
        corr = rep["diagnostic_rank_correlation_with_causal"]
        md.append("Spearman with the causal objective: " + ", ".join(f"{k} {f(v, 3)}" for k, v in corr.items()) + ".\n")
        sel = rep["selected_layer_set"]
        md.append(f"**Registered 18-block set (§4, chosen on SELECT2):** strategy `{sel['strategy']}`, removed {sel['removed']}; "
                  f"REPORT objective {sel['report_objective']:.4f}; REPORT-catastrophic: {sel['catastrophic_categories'] or 'none'}.\n")
        dsel = sel["depth"]
        rows18 = rep["strategies_by_depth"].get(str(dsel)) or rep["strategies_by_depth"].get(dsel) or []
        md += [f"| strategy @{dsel} | SELECT2 obj | REPORT obj | REPORT flip | removed |", "|---|---:|---:|---:|---|"]
        md += [f"| {r['strategy']} | {r['select2_objective']:.4f} | {r['report_objective']:.4f} | {r['flip_rate']:.3f} | {r['removed']} |"
               for r in rows18]
        fr = rep.get("frontier")
        if fr:
            md += ["\n**Iso-parameter frontier (§5):** " + fr["decision"] + "\n",
                   "| config | unique params | REPORT bpb | REPORT flip | registered |", "|---|---:|---:|---:|:--:|"]
            md += [f"| {p['vocab']}/{p['n_layers']} | {p['unique_params']:,} | {p['report_answer_bpb']:.4f} | {p['report_flip_rate']:.3f} | "
                   f"{'yes' if p['on_registered_frontier'] else ''} |" for p in fr["points"]]
            md.append("")
    else:
        md.append("pending (layer study running)\n")

    md.append("## 10–11. Depth and combined surgery (G2/G3)\n")
    arms = {k: _j(R / "arms" / k / "ARM_GATES.json") for k in ("A1", "A2", "A3")}
    if any(arms.values()):
        md += ["| arm | gates | unique params | bf16 file bytes | tests |", "|---|---|---:|---:|---|"]
        md += [f"| {k} | {g['G1_G2_G3']} | {g['unique_parameters']:,} | {g['out_file_bytes']:,} | {g['pytest_tail'][-1] if g['pytest_tail'] else ''} |"
               for k, g in arms.items() if g]
        md.append("")
    else:
        md.append("pending\n")

    md.append("## 13. Architecture manifests\n")
    archs = {k: _j(R / "arch" / f"ARCH_{k}.json") for k in ("A0", "A1", "A2", "A3")}
    if any(archs.values()):
        md += ["| arm | status | blocks | vocab rows | unique params | bf16 bytes | KV bytes/token (bf16) |", "|---|---|---:|---:|---:|---:|---:|"]
        md += [f"| {k} | {m['status']} | {m.get('n_layers', '—')} | {m['vocab_rows']:,} | {f(m.get('unique_parameters'))} | "
               f"{f(m.get('bf16_safetensors_bytes_exact'))} | {f((m.get('kv_cache_bytes_per_token') or {}).get('bf16'))} |"
               for k, m in archs.items() if m]
        md.append("")
    else:
        md.append("pending\n")

    md.append("## G4 — surgery-only damage by arm, V-SAFE, D-COLLAPSE (REPORT panels)\n")
    g4 = rep.get("G4") if rep else None
    if g4 and "limbs" in g4:
        md += ["| arm | config | REPORT answer bpb | REPORT flip | catastrophic |", "|---|---|---:|---:|---|"]
        md += [f"| {k} | {g4['arms'][k]} | {l['report_answer_bpb']:.4f} | {l['report_flip_rate']:.3f} | {', '.join(l['catastrophic_categories']) or '—'} |"
               for k, l in g4["limbs"].items()]
        ad = g4.get("additivity_report")
        if ad:
            md.append(f"\nAdditivity (descriptive): Δ(A1) {ad['delta_vs_A0']['A1']:+.4f}, Δ(A2) {ad['delta_vs_A0']['A2']:+.4f}, "
                      f"Δ(A3) {ad['delta_vs_A0']['A3']:+.4f} bpb; interaction {ad['interaction_A3_minus_A1_minus_A2']:+.4f} "
                      f"[{ad['interaction_bootstrap_95'][0]:+.4f}, {ad['interaction_bootstrap_95'][1]:+.4f}].\n")
        md.append(f"G4 (calibration panels) **{g4['G4_calibration_panels']}**; full G4: {g4['G4_full']}. "
                  f"V-SAFE **{g4['V_SAFE_A1_no_catastrophic']}**. D-COLLAPSE **{g4['D_COLLAPSE']}** "
                  f"(recommended student {g4['recommended_student']}); recovery_protected_categories: "
                  f"{', '.join(g4['recovery_protected_categories']) or 'none'}.\n")
    else:
        md.append("pending\n")

    lc = _j(R / "lc_arms" / "LC_ARMS.json")
    md.append("## Exploratory arm H-LC (training-free linear compensation)\n")
    if lc:
        h = lc["H_LC"]
        md.append(f"**{h['verdict']}** — r = {h['relative_reduction_r']:+.3f}, bootstrap 95% [{h['bootstrap_95'][0]:+.3f}, "
                  f"{h['bootstrap_95'][1]:+.3f}]; observed spread {h['s_ratio_hat']:.3f} (band {h.get('calibration_band')}); "
                  f"shape skew {h['skew']:+.2f}, excess kurtosis {h['excess_kurtosis']:+.2f}, "
                  f"corr(log kl, log ratio) {h['corr_logkl_logratio']:+.3f}; harm detectability {h.get('harm_detectability')}. "
                  f"L2-vs-KL proxy: {lc['proxy_L2_vs_KL']}.\n")
    else:
        md.append("pending\n")

    d = go_hold.decide(R, R / "layer_study" / "LAYER_REPORT.json", R / "arms", R / "lc_arms" / "LC_ARMS.json")
    md += ["## 15. Pre-distillation evaluation plan\n", "`PREDISTILLATION_EVAL_PLAN.md` (the qualified shim is not built; full G4 pending).\n",
           "## 16. Recommended first student\n",
           (json.dumps(d["recommendation"], indent=1) if d["recommendation"] else "pending") + "\n",
           "## 17. GO / HOLD for recovery\n",
           f"**{d['decision']}**. Failing: {d['failing'] or 'none'}. Missing: {', '.join(d['missing']) or 'none'}.\n",
           "| limb | state | detail |", "|---|---|---|"]
    md += [f"| {k} | {v['state']} | {v['detail']} |" for k, v in d["limbs"].items()]
    a.out.write_text("\n".join(md) + "\n", encoding="utf-8", newline="\n")
    print(f"wrote {a.out} | decision {d['decision']} | missing {len(d['missing'])}")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
